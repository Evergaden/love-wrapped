const INDEX = {}
CITIES.forEach((city) => {
  INDEX[city[0]] = { name: city[0], lat: city[1], lng: city[2] }
})

// 收拾用户写的一个名字：去空格和常见的行政后缀。
function cleanName(name) {
  let s = String(name || '').trim()
  s = s.replace(/\s+/g, '')
  s = s.replace(/(特别行政区|自治州|自治县|地区|自治区|省|市|盟|县|区)$/g, '')
  return s
}

// 拿一个名字去坐标库里找城市/国家。找不到返回 null，调用方自己兜底。
function find(name) {
  const cleaned = cleanName(name)
  if (!cleaned || cleaned.length < 2) return null
  if (INDEX[cleaned]) return INDEX[cleaned]
  // 包含匹配取最长：「泰国普吉岛」优先命中普吉岛而不是泰国。
  let hit = null
  CITIES.forEach((city) => {
    if (cleaned.indexOf(city[0]) >= 0) {
      if (!hit || city[0].length > hit.name.length) hit = INDEX[city[0]]
    }
  })
  if (hit) return hit
  // 前缀兜底：「杭州湾」这类开头写法。
  CITIES.some((city) => {
    if (city[0].indexOf(cleaned) >= 0) {
      hit = INDEX[city[0]]
      return true
    }
    return false
  })
  return hit
}

// 把「杭州、大理 成都」这样的整行拆成一个个名字，顺手去重。
function splitPlaces(text) {
  const seen = {}
  const list = []
  String(text || '')
    .split(/[、，,;；\/、\s\n]+/)
    .forEach((raw) => {
      const name = cleanName(raw)
      if (!name || seen[name]) return
      seen[name] = true
      list.push(name)
    })
  return list
}

// 两点之间的直线距离，单位公里。够估算用，别当导航。
function distanceKm(a, b) {
  if (!a || !b) return null
  const rad = Math.PI / 180
  const dLat = (b.lat - a.lat) * rad
  const dLng = (b.lng - a.lng) * rad
  const s = Math.sin(dLat / 2) * Math.sin(dLat / 2)
    + Math.cos(a.lat * rad) * Math.cos(b.lat * rad)
    * Math.sin(dLng / 2) * Math.sin(dLng / 2)
  const km = Math.round(2 * 6371 * Math.asin(Math.sqrt(s)))
  // 远距离取整到十位，看起来更像「差不多」而不是装精确。
  return km >= 100 ? Math.round(km / 10) * 10 : km
}

